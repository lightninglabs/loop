var lostResponse = errors.New("sign response lost")

// testWallet exercises LND's real session manager behind its RPC-shaped API.
// Private keys exist only in this test wallet, never in the production signer.
type testWallet struct {
	signrpc.SignerClient
	walletrpc.WalletKitClient
	t          *testing.T
	key        *btcec.PrivateKey
	manager    *input.MusigSessionManager
	mu         sync.Mutex
	creates    int
	signs      int
	lost       bool
	last       []byte
	mutate     func(*signrpc.MuSig2SessionResponse)
	badPartial bool
	badRaw     bool
	afterSign  func()
}

func newTestWallet(t *testing.T) *testWallet {
	t.Helper()
	key, _ := btcec.PrivKeyFromBytes([]byte{2})
	w := &testWallet{t: t, key: key}
	w.restart()
	return w
}

func (w *testWallet) restart() {
	w.manager = input.NewMusigSessionManager(func(
		key *keychain.KeyDescriptor) (*btcec.PrivateKey, error) {

		if key.KeyLocator != testLocator() {
			return nil, ErrBinding
		}
		return w.key, nil
	})
}

func testLocator() keychain.KeyLocator {
	return keychain.KeyLocator{Family: 99, Index: 3}
}

func (w *testWallet) DeriveKey(_ context.Context,
	key *signrpc.KeyLocator, _ ...grpc.CallOption) (
	*signrpc.KeyDescriptor, error) {

	return &signrpc.KeyDescriptor{
		KeyLoc: key, RawKeyBytes: w.key.PubKey().SerializeCompressed(),
	}, nil
}

func (w *testWallet) MuSig2CreateSession(_ context.Context,
	request *signrpc.MuSig2SessionRequest, _ ...grpc.CallOption) (
	*signrpc.MuSig2SessionResponse, error) {

	w.mu.Lock()
	defer w.mu.Unlock()
	w.creates++
	require.Len(w.t, request.PregeneratedLocalNonce, musig2.SecNonceSize)
	var nonces musig2.Nonces
	copy(nonces.SecNonce[:], request.PregeneratedLocalNonce)
	for i := 0; i < 2; i++ {
		_, point := btcec.PrivKeyFromBytes(
			nonces.SecNonce[i*32 : (i+1)*32],
		)
		copy(nonces.PubNonce[i*33:(i+1)*33],
			point.SerializeCompressed())
	}
	keys := make([]*btcec.PublicKey, len(request.AllSignerPubkeys))
	for i, raw := range request.AllSignerPubkeys {
		var err error
		keys[i], err = btcec.ParsePubKey(raw)
		require.NoError(w.t, err)
	}
	peers := make([][musig2.PubNonceSize]byte,
		len(request.OtherSignerPublicNonces))
	for i, nonce := range request.OtherSignerPublicNonces {
		copy(peers[i][:], nonce)
	}
	info, err := w.manager.MuSig2CreateSession(input.MuSig2Version100RC2,
		testLocator(), keys, &input.MuSig2Tweaks{
			TaprootBIP0086Tweak: request.TaprootTweak.KeySpendOnly,
			TaprootTweak:        request.TaprootTweak.ScriptRoot,
		}, peers, &nonces)
	if err != nil {
		return nil, err
	}
	internal := schnorr.SerializePubKey(info.TaprootInternalKey)
	response := &signrpc.MuSig2SessionResponse{
		SessionId:          info.SessionID[:],
		CombinedKey:        schnorr.SerializePubKey(info.CombinedKey),
		TaprootInternalKey: internal,
		LocalPublicNonces:  info.PublicNonce[:],
		HaveAllNonces:      info.HaveAllNonces,
		Version:            muSigVersion,
	}
	if w.mutate != nil {
		w.mutate(response)
	}
	return response, nil
}

func (w *testWallet) MuSig2Sign(_ context.Context,
	request *signrpc.MuSig2SignRequest, _ ...grpc.CallOption) (
	*signrpc.MuSig2SignResponse, error) {

	w.mu.Lock()
	defer w.mu.Unlock()
	w.signs++
	var id input.MuSig2SessionID
	copy(id[:], request.SessionId)
	var message [32]byte
	copy(message[:], request.MessageDigest)
	partial, err := w.manager.MuSig2Sign(id, message, request.Cleanup)
	if err != nil {
		return nil, err
	}
	var encoded bytes.Buffer
	require.NoError(w.t, partial.Encode(&encoded))
	w.last = encoded.Bytes()
	if w.afterSign != nil {
		w.afterSign()
	}
	if w.lost {
		return nil, lostResponse
	}
	if w.badPartial {
		return &signrpc.MuSig2SignResponse{
			LocalPartialSignature: make([]byte, 32),
		}, nil
	}
	return &signrpc.MuSig2SignResponse{
		LocalPartialSignature: bytes.Clone(w.last),
	}, nil
}

