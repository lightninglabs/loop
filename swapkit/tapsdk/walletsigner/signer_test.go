type signingFixture struct {
	t       *testing.T
	path    string
	s       *Signer
	w       *testWallet
	pkg     *sdk.CustomAnchorTransferPackage
	request sdk.CustomAnchorMuSig2SigningRequest
	id      [32]byte
	peerKey *btcec.PrivateKey
	peer    *musig2.Nonces
	public  [musig2.PubNonceSize]byte
}

func newSigningFixture(t *testing.T,
	changes ...func(*sdk.CustomAnchorTransferPackage)) *signingFixture {

	t.Helper()
	f := &signingFixture{
		t: t, path: filepath.Join(t.TempDir(), "signer.db"),
		w: newTestWallet(t), pkg: testPackage(t, "musig"),
		id: [32]byte{7},
	}
	for _, change := range changes {
		change(f.pkg)
	}
	var err error
	f.s, err = Open(f.path, f.w, f.w)
	require.NoError(t, err)
	t.Cleanup(func() { require.NoError(t, f.s.Close()) })
	requests, err := f.pkg.SigningRequests()
	require.NoError(t, err)
	require.Len(t, requests.MuSig2, 1)
	f.request = requests.MuSig2[0]
	f.peerKey, _ = btcec.PrivKeyFromBytes([]byte{3})
	f.peer, err = musig2.GenNonces(musig2.WithPublicKey(f.peerKey.PubKey()))
	require.NoError(t, err)
	f.public, err = f.s.Nonce(t.Context(), f.id, testLocator(),
		f.pkg, f.request.ID)
	require.NoError(t, err)
	return f
}

func (f *signingFixture) peers() []PeerNonce {
	public, err := sdk.ParsePubKey(f.peerKey.PubKey().SerializeCompressed())
	require.NoError(f.t, err)
	return []PeerNonce{{PublicKey: public, Nonce: f.peer.PubNonce}}
}

func (f *signingFixture) reopen() {
	require.NoError(f.t, f.s.Close())
	var err error
	f.s, err = Open(f.path, f.w, f.w)
	require.NoError(f.t, err)
}

func (f *signingFixture) peerPartial() []PeerPartial {
	combined, err := musig2.AggregateNonces([][musig2.PubNonceSize]byte{
		f.public, f.peer.PubNonce,
	})
	require.NoError(f.t, err)
	keys := make([]*btcec.PublicKey, len(f.request.Participants))
	for i, key := range f.request.Participants {
		keys[i], err = btcec.ParsePubKey(key[:])
		require.NoError(f.t, err)
	}
	option := musig2.WithTaprootSignTweak(f.request.TaprootMerkleRoot)
	if len(f.request.TaprootMerkleRoot) == 0 {
		option = musig2.WithBip86SignTweak()
	}
	partial, err := musig2.Sign(f.peer.SecNonce, f.peerKey, combined,
		keys, f.request.Sighash, option)
	require.NoError(f.t, err)
	var encoded bytes.Buffer
	require.NoError(f.t, partial.Encode(&encoded))
	return []PeerPartial{{
		PublicKey: f.peers()[0].PublicKey, Signature: encoded.Bytes(),
	}}
}

func TestNonceAndPartialRecoverAfterWalletRestart(t *testing.T) {
	f := newSigningFixture(t)
	stat, err := os.Stat(f.path)
	require.NoError(t, err)
	require.Equal(t, os.FileMode(0600), stat.Mode().Perm())
	f.reopen()
	f.w.restart()
	nonce, err := f.s.Nonce(t.Context(), f.id, testLocator(),
		f.pkg, f.request.ID)
	require.NoError(t, err)
	require.Equal(t, f.public, nonce)
	require.Zero(t, f.w.creates)

	// The wallet signed, but the RPC reply was lost before the application
	// could persist it. Both processes may restart at this boundary.
	f.w.lost = true
	_, err = f.s.Sign(t.Context(), f.id, f.peers())
	require.ErrorIs(t, err, lostResponse)
	expected := bytes.Clone(f.w.last)
	f.reopen()
	f.w.restart()
	f.w.lost = false
	partial, err := f.s.Sign(t.Context(), f.id, f.peers())
	require.NoError(t, err)
	require.Equal(t, expected, partial.Signature)
	require.Equal(t, f.public, partial.Nonce)
	require.Equal(t, 2, f.w.signs)
	f.reopen()
	f.w.restart()
	again, err := f.s.Sign(t.Context(), f.id, f.peers())
	require.NoError(t, err)
	require.Equal(t, partial, again)
	require.Equal(t, 2, f.w.signs)
	r, err := f.s.load(t.Context(), f.id)
	require.NoError(t, err)
	require.Equal(t, [musig2.SecNonceSize]byte{}, r.Secret)

	// Combination needs no live wallet session and SDK verifies the final
	// aggregate signature against the exact committed Bitcoin prevout.
	peers := f.peerPartial()
	signature, err := f.s.Combine(t.Context(), f.id, peers)
	require.NoError(t, err)
	_, err = f.pkg.ApplyKeyPathSignature(
		f.request.ID, signature,
	)
	require.NoError(t, err)
	peers[0].Signature[0] ^= 1
	_, err = f.s.Combine(t.Context(), f.id, peers)
	require.ErrorIs(t, err, ErrInvalid)
}

func TestBindingRejectsChangedRoundAndPeer(t *testing.T) {
	f := newSigningFixture(t)
	ctx := t.Context()
	_, err := f.s.Nonce(ctx, f.id, keychain.KeyLocator{Family: 100},
		f.pkg, f.request.ID)
	require.ErrorIs(t, err, ErrBinding)
	_, err = f.s.Nonce(ctx, f.id, testLocator(), f.pkg, sdk.Hash{8})
	require.ErrorIs(t, err, ErrBinding)
	changed := f.pkg.Clone()
	changed.Publish.Label = "another approved package"
	changed, err = changed.Seal()
	require.NoError(t, err)
	_, err = f.s.Nonce(ctx, f.id, testLocator(), changed, f.request.ID)
	require.ErrorIs(t, err, ErrBinding)

	f.w.lost = true
	_, err = f.s.Sign(ctx, f.id, f.peers())
	require.ErrorIs(t, err, lostResponse)
	f.reopen()
	other, err := musig2.GenNonces(musig2.WithPublicKey(f.peerKey.PubKey()))
	require.NoError(t, err)
	peers := f.peers()
	peers[0].Nonce = other.PubNonce
	_, err = f.s.Sign(ctx, f.id, peers)
	require.ErrorIs(t, err, ErrBinding)
	require.Equal(t, 1, f.w.signs)
	peers = f.peers()
	peers[0].PublicKey[0] ^= 1
	_, err = f.s.Sign(ctx, f.id, peers)
	require.ErrorIs(t, err, ErrBinding)
	_, err = f.s.Sign(ctx, f.id, nil)
	require.ErrorIs(t, err, ErrInvalid)
}

func TestWalletResponsesCheckedBeforePartialExposure(t *testing.T) {
	cases := map[string]func(*signrpc.MuSig2SessionResponse){
		"nonce": func(r *signrpc.MuSig2SessionResponse) {
			r.LocalPublicNonces[0] ^= 1
		},
		"combined key": func(r *signrpc.MuSig2SessionResponse) {
			r.CombinedKey[0] ^= 1
		},
		"internal key": func(r *signrpc.MuSig2SessionResponse) {
			r.TaprootInternalKey[0] ^= 1
		},
		"missing nonce": func(r *signrpc.MuSig2SessionResponse) {
			r.HaveAllNonces = false
		},
	}
	for name, mutate := range cases {
		t.Run(name, func(t *testing.T) {
			f := newSigningFixture(t)
			f.w.mutate = mutate
			_, err := f.s.Sign(t.Context(), f.id, f.peers())
			require.ErrorIs(t, err, ErrInvalid)
			require.Zero(t, f.w.signs)
			r, err := f.s.load(t.Context(), f.id)
			require.NoError(t, err)
			require.NotEmpty(t, r.Peers)
			require.Empty(t, r.Signature)
		})
	}
	t.Run("invalid partial", func(t *testing.T) {
		f := newSigningFixture(t)
		f.w.badPartial = true
		_, err := f.s.Sign(t.Context(), f.id, f.peers())
		require.ErrorIs(t, err, ErrInvalid)
		f.w.badPartial = false
		_, err = f.s.Sign(t.Context(), f.id, f.peers())
		require.NoError(t, err)
	})
}

func TestCorruptNonceFailsBeforeWalletRPC(t *testing.T) {
	f := newSigningFixture(t)
	err := f.s.db.Update(func(tx *bbolt.Tx) error {
		bucket := tx.Bucket(roundsBucket)
		raw := bytes.Clone(bucket.Get(f.id[:]))
		// A changed embedded key is detected against
		// the stored wallet key before any session can be created.
		var r round
		require.NoError(t, json.Unmarshal(raw, &r))
		r.Secret[64] ^= 1
		raw, err := json.Marshal(r)
		require.NoError(t, err)
		return bucket.Put(f.id[:], raw)
	})
	require.NoError(t, err)
	_, err = f.s.Sign(t.Context(), f.id, f.peers())
	require.ErrorIs(t, err, ErrInvalid)
	require.Zero(t, f.w.creates)
}

func (w *testWallet) SignOutputRaw(_ context.Context,
	request *signrpc.SignReq, _ ...grpc.CallOption) (
	*signrpc.SignResp, error) {

	var transaction wire.MsgTx
	require.NoError(w.t, transaction.Deserialize(
		bytes.NewReader(request.RawTxBytes),
	))
	require.Len(w.t, request.PrevOutputs, len(transaction.TxIn))
	require.Len(w.t, request.SignDescs, 1)
	descriptor := request.SignDescs[0]
	fetcher := txscript.NewMultiPrevOutFetcher(nil)
	for i, previous := range request.PrevOutputs {
		fetcher.AddPrevOut(transaction.TxIn[i].PreviousOutPoint,
			&wire.TxOut{
				Value:    previous.Value,
				PkScript: previous.PkScript,
			})
	}
	hashes := txscript.NewTxSigHashes(&transaction, fetcher)
	require.Equal(w.t,
		signrpc.SignMethod_SIGN_METHOD_TAPROOT_SCRIPT_SPEND,
		descriptor.SignMethod)
	signature, err := txscript.RawTxInTapscriptSignature(
		&transaction, hashes, int(descriptor.InputIndex),
		descriptor.Output.Value, descriptor.Output.PkScript,
		txscript.NewBaseTapLeaf(descriptor.WitnessScript),
		txscript.SigHashType(descriptor.Sighash), w.key,
	)
	require.NoError(w.t, err)
	if w.badRaw {
		signature[0] ^= 1
	}
	return &signrpc.SignResp{RawSigs: [][]byte{signature[:64]}}, nil
}

