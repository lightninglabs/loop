func TestTweakedAggregateAndExplicitSighash(t *testing.T) {
	for _, sighash := range []txscript.SigHashType{
		txscript.SigHashDefault, txscript.SigHashAll,
	} {
		t.Run(fmt.Sprint(uint32(sighash)), func(t *testing.T) {
			change := func(pkg *sdk.CustomAnchorTransferPackage) {
				packet, err := psbt.NewFromRawBytes(
					bytes.NewReader(pkg.AnchorPsbt), false,
				)
				require.NoError(t, err)
				root := bytes.Repeat([]byte{42}, 32)
				internal, err := schnorr.ParsePubKey(
					packet.Inputs[1].TaprootInternalKey,
				)
				require.NoError(t, err)
				output := txscript.ComputeTaprootOutputKey(
					internal, root,
				)
				packet.Inputs[1].WitnessUtxo.PkScript, err =
					txscript.PayToTaprootScript(output)
				require.NoError(t, err)
				packet.Inputs[1].TaprootMerkleRoot = root
				packet.Inputs[1].SighashType = sighash
				var raw bytes.Buffer
				require.NoError(t, packet.Serialize(&raw))
				pkg.AnchorPsbt = raw.Bytes()
				pkg.CommittedAnchorPsbt = nil
				pkg.SchemaVersion = 0
				pkg.PackageDigest = sdk.Hash{}
				pkg.CommittedPackageDigest = sdk.Hash{}
				pkg.UnsignedTxDigest = sdk.Hash{}
				sealed, err := pkg.Seal()
				require.NoError(t, err)
				*pkg = *sealed
			}
			f := newSigningFixture(t, change)
			_, err := f.s.Sign(t.Context(), f.id, f.peers())
			require.NoError(t, err)
			signature, err := f.s.Combine(
				t.Context(), f.id, f.peerPartial(),
			)
			require.NoError(t, err)
			length := 64
			if sighash != txscript.SigHashDefault {
				length++
			}
			require.Len(t, signature, length)
			_, err = f.pkg.ApplyKeyPathSignature(
				f.request.ID, signature,
			)
			require.NoError(t, err)
		})
	}
}

func TestCanceledJournalWriteNeverReturnsPartial(t *testing.T) {
	f := newSigningFixture(t)
	ctx, cancel := context.WithCancel(t.Context())
	defer cancel()
	f.w.afterSign = cancel
	partial, err := f.s.Sign(ctx, f.id, f.peers())
	require.Nil(t, partial)
	require.ErrorIs(t, err, context.Canceled)
	expected := bytes.Clone(f.w.last)
	r, err := f.s.load(t.Context(), f.id)
	require.NoError(t, err)
	require.Empty(t, r.Signature)
	require.NotEmpty(t, r.Peers)
	f.reopen()
	f.w.restart()
	f.w.afterSign = nil
	partial, err = f.s.Sign(t.Context(), f.id, f.peers())
	require.NoError(t, err)
	require.Equal(t, expected, partial.Signature)
}
