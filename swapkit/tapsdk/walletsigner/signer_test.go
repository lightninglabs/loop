func TestConcurrentDifferentPeersCannotReuseNonce(t *testing.T) {
	f := newSigningFixture(t)
	other, err := musig2.GenNonces(musig2.WithPublicKey(f.peerKey.PubKey()))
	require.NoError(t, err)
	first, second := f.peers(), f.peers()
	second[0].Nonce = other.PubNonce
	errors := make(chan error, 2)
	for _, peers := range [][]PeerNonce{first, second} {
		go func() {
			_, err := f.s.Sign(t.Context(), f.id, peers)
			errors <- err
		}()
	}
	a, b := <-errors, <-errors
	if a == nil {
		require.ErrorIs(t, b, ErrBinding)
	} else {
		require.ErrorIs(t, a, ErrBinding)
		require.NoError(t, b)
	}
	require.Equal(t, 1, f.w.signs)
}

